import { useSyncExternalStore } from 'react';
import { I18nManager } from 'react-native';
import * as SecureStore from 'expo-secure-store';

/**
 * English and Arabic for the app. The English text is the key, so anything without a translation simply shows in
 * English. The language follows the phone's language the first time, then whatever the person picks (About screen).
 * Right-to-left layout only takes effect after the app is closed and opened again; the words change at once.
 */
export type Lang = 'en' | 'ar';

const KEY = 'tably.lang';

function initial(): Lang {
  try {
    const saved = SecureStore.getItem(KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch { /* not available */ }
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('ar') ? 'ar' : 'en';
  } catch {
    return 'en';
  }
}

let lang: Lang = initial();
const listeners = new Set<() => void>();

try {
  I18nManager.allowRTL(true);
  if (I18nManager.isRTL !== (lang === 'ar')) I18nManager.forceRTL(lang === 'ar');
} catch { /* layout direction is a nicety */ }

/** True when the layout is already right-to-left (after a restart); false until then. */
export const layoutMatches = () => I18nManager.isRTL === (lang === 'ar');

export function setLang(next: Lang): void {
  lang = next;
  try { void SecureStore.setItemAsync(KEY, next); } catch { /* best effort */ }
  try { I18nManager.forceRTL(next === 'ar'); } catch { /* best effort */ }
  listeners.forEach((l) => l());
}

export function useLang(): Lang {
  return useSyncExternalStore((cb) => { listeners.add(cb); return () => listeners.delete(cb); }, () => lang);
}

export const currentLang = () => lang;
export const dateLocale = () => (lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB');

